// Enquete anônima (ninguém vê quem votou) e caixa de perguntas (com nome ou anônima) na publicação e no Flash.
process.env.FIRESTORE_EMULATOR_HOST = "127.0.0.1:8085";
import { initializeApp } from "firebase-admin/app"; import { getFirestore, Timestamp } from "firebase-admin/firestore";
import { navegador, entrar, USUARIOS as U, BASE } from "./nav.mjs";
const ok = (c, t) => { console.log(c ? "  ✔" : "  ✘", t); if (!c) process.exitCode = 1; };
initializeApp({ projectId: "demo-hf" }); const db = getFirestore();
for (const q of ["bruno", "dani"]) await db.doc(`relacoes/${U[q]}_${U.ana}`).set({ tipo: "seguir", seguidorId: U[q], alvoId: U.ana, criadoEm: Timestamp.now() });
await db.doc("diario/pCxNome").set({ autorId: U.ana, nome: "Ana Souza", texto: "Tirem dúvidas sobre reformas", caixa: { pergunta: "O que querem saber?", anonima: false }, criadoEm: Timestamp.fromMillis(Date.now() - 3600e3) });

const A = await navegador({ mobile: true, camera: true }), B = await navegador({ mobile: true }), D = await navegador({ mobile: true });
const pa = await entrar(A.ctx, "ana", "feed.html?aba=registros");
await pa.waitForSelector("#btnComporFeed", { timeout: 30000 }); await pa.waitForTimeout(1500);
// 1) Enquete anônima + caixa anônima numa publicação
await pa.locator("#btnComporFeed").tap();
await pa.locator("#pubTexto").fill("Opinem sem medo!");
await pa.locator("#pubEnqueteBtn").tap();
await pa.locator("#pubEnquete .pe-pergunta").fill("Gostam do novo logo?");
await pa.locator("#pubEnquete .pe-opcao input").nth(0).fill("Sim");
await pa.locator("#pubEnquete .pe-opcao input").nth(1).fill("Não");
await pa.locator("#pubEnquete .enq-chave").click();
await pa.locator(".folha#folhaPublicar .folha-corpo, #folhaPublicar").first().screenshot({ path: "saida/cx-compor.png" });
await pa.locator("#pubEnviar").click();
await pa.waitForFunction(() => !document.getElementById("folhaPublicar")?.classList.contains("aberta"), null, { timeout: 30000 }).catch(() => {});
await pa.waitForTimeout(1200);
const post = (await db.collection("diario").where("autorId", "==", U.ana).get()).docs.map((d) => ({ id: d.id, ...d.data() })).find((p) => p.texto === "Opinem sem medo!");
// Um tipo por publicação (Enquete OU Perguntas): a caixa anônima é testada na mesma publicação, posta pelo servidor
// (publicações antigas podem ter as duas).
if (post) { await db.doc(`diario/${post.id}`).update({ caixa: { pergunta: "Mande uma sugestão", anonima: true } }); post.caixa = { pergunta: "Mande uma sugestão", anonima: true }; }
// Pelo formulário, a caixa anônima: tipo Perguntas com a chave "Respostas anônimas".
await pa.locator("#btnComporFeed").tap(); await pa.waitForTimeout(500);
await pa.locator("#pubCaixaBtn").tap();
await pa.locator("#pubCaixa .pe-pergunta").fill("Caixa anônima pelo formulário");
await pa.locator("#pubCaixa .enq-chave").click();
await pa.locator("#pubEnviar").click();
await pa.waitForFunction(() => !document.getElementById("folhaPublicar")?.classList.contains("aberta"), null, { timeout: 30000 }).catch(() => {});
await pa.waitForTimeout(1200);
const pcx = (await db.collection("diario").where("autorId", "==", U.ana).get()).docs.map((d) => d.data()).find((p) => p.caixa?.pergunta === "Caixa anônima pelo formulário");
ok(pcx?.tipo === "caixa" && pcx.caixa.anonima === true, "formulário: Perguntas com respostas anônimas");
ok(post?.enquete?.anonima === true && post?.caixa?.anonima === true && post.caixa.pergunta === "Mande uma sugestão", "publicou com enquete anônima e caixa anônima");
// 2) Bruno vota (anônimo) e responde (anônimo); Dani responde a caixa com nome
const pb = await entrar(B.ctx, "bruno", "feed.html?aba=registros");
const cb = pb.locator(".post-card", { hasText: "Opinem sem medo" }).first();
await cb.waitFor({ timeout: 30000 }); await cb.scrollIntoViewIfNeeded(); await pb.waitForTimeout(1500);
ok(await cb.locator(".enquete .enq-anon").count() === 1 && /voto anônimo/.test(await cb.locator(".enq-rodape").textContent()), "Bruno vê a enquete marcada como Anônima");
await cb.locator(".enquete .enq-op", { hasText: "Sim" }).tap(); await pb.waitForTimeout(1500);
const va = await db.doc(`enquete_anon/d_${post.id}_${U.bruno}`).get(), ct = va.exists ? await db.doc(`enquete_contas/d_${post.id}_${va.data().fatia}`).get() : null;
ok(va.exists && Number.isInteger(va.data().fatia) && ct?.data()?.n0 === 1 && !(await db.doc(`enquete_votos/d_${post.id}_${U.bruno}`).get()).exists, "voto anônimo: em enquete_anon, pedaço da contagem n0 = 1, nada em enquete_votos");
ok((await cb.locator(".enquete .enq-op.minha").textContent()).includes("Sim") && (await cb.locator(".enquete .enq-pct").count()) === 0 && /Voto registrado \(anônimo\)/.test(await cb.locator(".enquete .enq-rodape").textContent()), "Bruno vê o voto marcado; o resultado só sai no fim");
await cb.locator(".caixa-perg textarea").fill("Coloca mais azul!");
await cb.locator(".caixa-perg .cx-enviar").tap(); await pb.waitForTimeout(1500);
const rs = (await db.collection("caixa_respostas").where("alvo", "==", "d_" + post.id).get()).docs;
ok(rs.length === 1 && !("uid" in rs[0].data()) && (await db.doc(`caixa_autoria/${rs[0].id}`).get()).data()?.uid === U.bruno, "resposta anônima: sem nome na resposta; autoria só para a moderação");
ok(/sem o seu nome/.test(await cb.locator(".caixa-perg .cx-nota").textContent()), "Bruno vê 'Resposta enviada sem o seu nome'");
await cb.locator(".caixa-perg").screenshot({ path: "saida/cx-bruno.png" });
const pd = await entrar(D.ctx, "dani", "feed.html?aba=registros");
const cdn = pd.locator(".post-card", { hasText: "Tirem dúvidas" }).first();
await cdn.waitFor({ timeout: 30000 }); await cdn.scrollIntoViewIfNeeded(); await pd.waitForTimeout(1200);
ok(/Seu nome aparece/.test(await cdn.locator(".caixa-perg .cx-nota").textContent()), "caixa com nome avisa que o nome aparece");
await cdn.locator(".caixa-perg textarea").fill("Quanto custa trocar o piso?");
await cdn.locator(".caixa-perg textarea").press("Enter"); await pd.waitForTimeout(1500);
ok((await db.collection("caixa_respostas").where("alvo", "==", "d_pCxNome").get()).docs[0]?.data().uid === U.dani, "Dani respondeu com o nome");
// 3) Ana: sem "Ver votos" na anônima; respostas
await pa.goto(BASE + `feed.html?post=${post.id}`);
const ca = pa.locator(".visor-exp .post-card", { hasText: "Opinem sem medo" }).first();
await ca.waitFor({ timeout: 30000 }); await ca.scrollIntoViewIfNeeded(); await pa.waitForTimeout(2000);
ok(await ca.locator(".enq-ver").count() === 0 && (await ca.locator(".enquete .enq-pct").first().textContent()) === "100%", "Ana vê o resultado da anônima, sem 'Ver votos'");
ok((await ca.locator(".cx-ver strong").textContent()) === "1", "Ana vê '1 resposta' na caixa");
await ca.screenshot({ path: "saida/cx-ana-post.png" });
await ca.locator(".cx-ver").tap();
await pa.waitForSelector("#listaCorpo .cx-resp", { timeout: 8000 });
ok((await pa.locator("#listaCorpo .cx-resp .quem strong").textContent()) === "Anônimo" && await pa.locator("#listaCorpo .cx-resp .avatar.anonimo").count() === 1 && await pa.locator("#listaCorpo .cx-resp button", { hasText: "Responder" }).count() === 0, "resposta anônima aparece como Anônimo, sem Responder");
await pa.screenshot({ path: "saida/cx-respostas-anon.png" });
await pa.locator("#folhaLista [data-fechar]").click(); await pa.waitForTimeout(300);
await pa.goto(BASE + "feed.html?post=pCxNome");
const cn = pa.locator(".visor-exp .post-card", { hasText: "Tirem dúvidas" }).first();
await cn.waitFor({ timeout: 30000 }); await pa.waitForTimeout(1500);
await cn.locator(".cx-ver").tap();
await pa.waitForSelector("#listaCorpo .cx-resp", { timeout: 8000 });
ok((await pa.locator("#listaCorpo .cx-resp .quem strong").textContent()).startsWith("Dani"), "resposta com nome mostra a Dani");
await pa.locator("#listaCorpo .cx-resp button", { hasText: "Responder" }).tap();
await pa.locator("#listaCorpo .cx-responder textarea").fill("Depende do material, te passo um orçamento!");
await pa.locator("#listaCorpo .cx-responder .cx-enviar").tap(); await pa.waitForTimeout(2000);
const ids = [U.ana, U.dani].sort();
const msgs = await db.collection(`conversas/${ids[0]}_${ids[1]}/mensagens`).get();
ok(msgs.docs.some((m) => /Sobre a sua resposta/.test(m.data().texto || "")), "Responder manda a mensagem para a Dani no Mensagens");
await pa.screenshot({ path: "saida/cx-respostas-nome.png" });
await pa.locator("#folhaLista [data-fechar]").click(); await pa.waitForTimeout(300);
// 4) Notificações da Ana
await pa.goto(pa.url().replace(/feed\.html.*/, "notificacoes.html"));
await pa.waitForSelector(".nt2-item", { timeout: 30000 }); await pa.waitForTimeout(2500);
const txt = await pa.locator("#listaAvisos").textContent();
ok(/Anônimo respondeu sua caixa de perguntas/.test(txt) && /Dani.*respondeu sua caixa de perguntas/.test(txt), "notificações: resposta anônima e com nome");
await pa.screenshot({ path: "saida/cx-notif.png" });
// 5) Flash com caixa anônima: Bruno responde por cima do flash
await pa.close();
const pf = await entrar(A.ctx, "ana", "usuarios.html");
await pf.waitForSelector("#meuPerfil .pf-mais-flash", { timeout: 30000 });
await pf.locator("#meuPerfil .pf-mais-flash").tap();
await pf.waitForSelector(".flash-criar .flash-cam-ui .flash-disparo", { timeout: 10000 });
await pf.waitForFunction(() => document.querySelector(".flash-cam")?.videoWidth > 0, null, { timeout: 8000 });
await pf.locator(".flash-disparo").tap();
await pf.waitForSelector(".flash-fotobox canvas.flash-foto", { timeout: 8000 }); await pf.waitForTimeout(500);
await pf.locator(".flash-ferr-btn[aria-label^='Figurinhas']").tap();
await pf.locator(".fig-op", { hasText: "Perguntas" }).tap(); await pf.waitForTimeout(300);
await pf.locator(".flash-enq-ed .enq-chave").click();
await pf.locator(".flash-enq-ed .fe-pronto").tap(); await pf.waitForTimeout(300);
ok(await pf.locator(".flash-camada .fe-cx").count() === 1, "Flash: figurinha de perguntas no cartão");
await pf.screenshot({ path: "saida/cx-flash-criar.png" });
await pf.locator(".flash-publicar").tap(); await pf.waitForTimeout(3000);
const st = (await db.collection("stories").where("autorId", "==", U.ana).get()).docs.map((d) => ({ id: d.id, ...d.data() })).find((x) => x.caixa);
ok(st?.caixa?.anonima === true, "flash publicado com caixa anônima");
await pb.reload(); await pb.waitForSelector(".story-circ", { timeout: 30000 }); await pb.waitForTimeout(1500);
await pb.locator(".story-circ:not(.meu)").first().tap();
await pb.waitForSelector(".story-visor .story-cx textarea", { timeout: 10000 });
await pb.locator(".story-visor .story-cx textarea").fill("Amei o flash!");
await pb.locator(".story-visor .story-cx .cx-enviar").tap(); await pb.waitForTimeout(1500);
const rf = (await db.collection("caixa_respostas").where("alvo", "==", "f_" + st.id).get()).docs;
ok(rf.length === 1 && rf[0].data().anonima === true && !("uid" in rf[0].data()), "Bruno respondeu a caixa do flash (anônimo)");
await pb.screenshot({ path: "saida/cx-flash-visor.png" });
await A.browser.close(); await B.browser.close(); await D.browser.close();
