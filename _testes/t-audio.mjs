import { navegador, entrar, USUARIOS } from "./nav.mjs";
const { browser, ctx } = await navegador({ mobile: true });
const p = await entrar(ctx, "bruno", `mensagens.html?conversa=${USUARIOS.conv}`);
await p.waitForSelector(".hf-audio", { timeout: 20000 });
await p.evaluate(() => document.querySelector(".hf-audio").scrollIntoView({ block: "center" }));
await p.waitForTimeout(1500);
const estado = () => p.evaluate(() => { const a = document.querySelector(".hf-audio"); return { tempo: a.querySelector(".hf-audio-tempo").textContent, vel: a.querySelector(".hf-audio-vel").textContent, alturas: [...a.querySelectorAll(".hf-audio-onda i")].slice(0, 10).map((i) => i.style.height).join(" "), on: a.querySelectorAll(".hf-audio-onda i.on").length, classe: a.className }; });
console.log("antes de tocar:", JSON.stringify(await estado()));
await p.locator(".hf-audio-play").first().tap();
await p.waitForTimeout(1500);
console.log("tocando 1,5 s:", JSON.stringify(await estado()));
await p.locator(".hf-audio-vel").first().tap(); await p.locator(".hf-audio-vel").first().tap();
const box = await p.locator(".hf-audio-onda").first().boundingBox();
await p.touchscreen.tap(box.x + box.width * 0.75, box.y + box.height / 2);
await p.waitForTimeout(300);
console.log("velocidade 2x + pulou para 75%:", JSON.stringify(await estado()));
await p.screenshot({ path: "saida/audio-usuarios.png" });
await p.waitForTimeout(2500);
console.log("terminou:", JSON.stringify(await estado()));
console.log("onda guardada no aparelho:", await p.evaluate(() => Object.keys(JSON.parse(localStorage.getItem("hf-ondas") || "{}")).length));
await browser.close();
